// Bundles the public design-system stylesheet into the backend asset root.
//
// KetJS modules own one static asset directory. Production already copied the
// design-system source beneath that directory, but source-mode development did
// not, leaving the foundational stylesheet at an unversioned 404 URL. A single
// generated entry gives development and production the same immutable asset.

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'packages/design-system/src/styles.css')
const OUTPUT = join(ROOT, 'packages/ketsuite/src/modules/backend/design/design-system.css')

export async function buildBackendDesignSystem() {
  const result = await esbuild.build({
    entryPoints: [SOURCE],
    bundle: true,
    write: false,
    minify: true,
    platform: 'browser',
    target: 'es2022',
    banner: {
      css: '/* Generated by tools/build-backend-design-system.mjs — do not edit. */',
    },
    logLevel: 'warning',
  })
  const next = result.outputFiles[0]?.contents
  if (!next) throw new Error('design-system stylesheet build produced no output')
  const current = await readFile(OUTPUT).catch(() => null)
  if (!current?.equals(next)) await writeFile(OUTPUT, next)
  return OUTPUT
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await buildBackendDesignSystem()
  console.log('bundled backend design-system stylesheet')
}
