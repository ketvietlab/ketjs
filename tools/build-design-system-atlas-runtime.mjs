// Bundles the KetAtlas island runtime (atlas/island-runtime.ts) into a single,
// self-contained script with zero imports or exports — unlike the other client
// builders here, @ketvietlab/ketjs-view is bundled IN rather than resolved to the
// framework's /_ket/view/index.js, because a KetAtlas mock is a self-contained HTML
// document with no ketjs server behind it to serve that URL.
//
// atlas-cli.ts reads this output verbatim (the same way it reads runtime/index.js)
// and appends it to the materialized KetAtlas runtime asset.

import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'packages/design-system/src/atlas/relation-select-hydration.ts')
const OUTFILE = join(ROOT, 'packages/design-system/src/atlas/island-runtime.mjs')

export async function buildDesignSystemAtlasRuntime() {
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    sourcemap: false,
    // tsconfig.build.json's `include` glob has no extension filter, so this
    // minified bundle is still part of the TS program; @ts-nocheck is what keeps
    // tsc from trying (and failing) to infer types through it, matching every
    // other generated island bundle in this repo.
    banner: {
      js: '// @ts-nocheck Generated by tools/build-design-system-atlas-runtime.mjs — do not edit.',
    },
    logLevel: 'warning',
  })
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await buildDesignSystemAtlasRuntime()
  console.log(`bundled the KetAtlas island runtime into ${OUTFILE}`)
}
