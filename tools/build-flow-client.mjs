// Bundles the Flow collaborative editor's client-side TypeScript (which
// imports yjs, a real npm dependency) into one self-contained ESM file the
// framework can serve verbatim. This remains separate from the backend island
// builder because Flow also bundles the yjs dependency, while the backend
// islands only compile typed TSX and keep the shared view runtime external.
//
// The output lands next to the kit's other client assets, which is where
// flow_backend points its `assets` URL — the same arrangement mail_backend
// uses for the chatter.

import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

/**
 * The view runtime is served by the framework at a fixed URL, so it is
 * resolved to that URL rather than bundled — the same plugin
 * tools/build-backend-client.mjs uses, and for a reason worth stating: a
 * bundled second copy is not merely bigger, it is a *different* runtime. Its
 * `TemplateResult`s fail the page runtime's `isResult()` check, so an island's
 * whole child list stringified to `[object Object]` and hydration died on
 * "expected a text node". This file used to say `external: ['/_ket/view/index.js']`,
 * which was right while the entry was hand-written `.mjs` importing that URL
 * literally; once it became `.tsx` importing `@ketvietlab/ketjs-view`, the
 * pattern matched nothing and the runtime came along silently.
 */
/** @type {import('esbuild').Plugin} */
const ketViewRuntime = {
  name: 'ket-view-runtime',
  setup(build) {
    build.onResolve({ filter: /^@ketvietlab\/ketjs-view$/ }, () => ({
      path: '/_ket/view/index.js',
      external: true,
    }))
    build.onResolve({ filter: /^@ketvietlab\/ketjs-view\/jsx-runtime$/ }, () => ({
      path: '/_ket/view/jsx-runtime.js',
      external: true,
    }))
  },
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const UI_DIR = join(ROOT, 'packages/ketsuite/src/ui/client')
const ENTRY = join(UI_DIR, 'live-doc-view.tsx')
const OUTFILE = join(UI_DIR, 'live-doc.mjs')

export async function buildFlowClient() {
  if (!existsSync(ENTRY)) return false
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    // External rather than linked: a minified bundle's map inlines the
    // whole original source, so it is not something the asset mount will
    // serve (packages/ketjs/src/server/http.ts). Writing it without the
    // `sourceMappingURL` comment keeps it on disk for anyone debugging
    // locally without pointing every browser at a URL that must 404.
    sourcemap: 'external',
    // Every .mjs under the kit's client directory carries this, and the
    // generated one is no different: tsconfig.build.json type-checks that
    // directory, and a minified yjs bundle is not code TypeScript can have an
    // opinion about.
    banner: { js: '// @ts-nocheck Generated by tools/build-flow-client.mjs — do not edit.' },
    logLevel: 'warning',
    plugins: [ketViewRuntime],
  })
  return true
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const built = await buildFlowClient()
  console.log(
    built ? `bundled flow_backend client into ${OUTFILE}` : 'flow_backend has no client entry yet, skipped',
  )
}
