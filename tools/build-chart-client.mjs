// Bundles the chart island's client-side TypeScript (which imports chart.js, a
// real npm dependency) into one self-contained ESM file the framework can serve
// verbatim.
//
// Separate from tools/build-backend-client.mjs for the reason that file states
// about itself: the backend island builder compiles typed TSX and keeps the
// shared view runtime external, and nothing else. This one also pulls a
// dependency into the output, which is the same job tools/build-flow-client.mjs
// does for yjs — so it is that file's shape, not the island builder's.
//
// The output lands in the backend module's own assets directory rather than
// beside the kit's other client sources, because the chart island is declared by
// `backend` and `backend` points its `assets` URL at `design/`. Flow puts its
// bundle in the kit's client directory for the mirror-image reason: flow_backend
// points `assets` there.

import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

/**
 * The view runtime is served by the framework at a fixed URL, so it is resolved
 * to that URL rather than bundled. Copied from the other two client builders,
 * and for the reason spelled out in tools/build-flow-client.mjs: a bundled
 * second copy is not merely bigger, it is a *different* runtime, and an island
 * built against it fails the page runtime's `isResult()` check.
 */
/** @type {import('esbuild').Plugin} */
const ketViewRuntime = {
  name: 'ket-view-runtime',
  setup(build) {
    build.onResolve({ filter: /^@ketvietlab\/ketjs-view$/ }, () => ({
      path: '/_ket/view/index.js',
      external: true,
    }))
    build.onResolve({ filter: /^@ketvietlab\/ketjs-view\/jsx-runtime$/ }, () => ({
      path: '/_ket/view/jsx-runtime.js',
      external: true,
    }))
  },
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'packages/ketsuite/src/ui/client/chart-view.tsx')
const OUTFILE = join(ROOT, 'packages/ketsuite/src/modules/backend/design/client/chart.mjs')

export async function buildChartClient() {
  if (!existsSync(ENTRY)) return false
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    // External rather than linked: a minified bundle's map inlines the whole
    // original source, so it is not something the asset mount will serve
    // (packages/ketjs/src/server/http.ts). Writing it without the
    // `sourceMappingURL` comment keeps it on disk for anyone debugging locally
    // without pointing every browser at a URL that must 404.
    sourcemap: 'external',
    // Every .mjs under the backend's client directory carries this, and the
    // generated one is no different: tsconfig.build.json type-checks that
    // directory, and a minified chart.js bundle is not code TypeScript can have
    // an opinion about.
    banner: { js: '// @ts-nocheck Generated by tools/build-chart-client.mjs — do not edit.' },
    logLevel: 'warning',
    plugins: [ketViewRuntime],
  })
  return true
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const built = await buildChartClient()
  console.log(
    built ? `bundled the chart island into ${OUTFILE}` : 'the chart island has no entry yet, skipped',
  )
}
