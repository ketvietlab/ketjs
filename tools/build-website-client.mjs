import { cpSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export async function buildWebsiteClient() {
  const out = resolve(root, 'packages/ketsuite/src/modules/website_backend/client')
  mkdirSync(out, { recursive: true })
  // Bundle the same pure renderer used by the builder into the server package.
  await build({
    entryPoints: [resolve(root, 'packages/website-client/client/renderer.tsx')],
    outfile: resolve(out, 'public-renderer.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    external: ['@ketvietlab/ketjs-view', '@ketvietlab/ketjs-view/jsx-runtime'],
    jsx: 'automatic',
    jsxImportSource: '@ketvietlab/ketjs-view',
    banner: { js: '// @ts-nocheck Generated by build-website-client.mjs' },
  })
  await build({
    stdin: {
      contents: [
        'packages/ketsuite/src/ui/client/live-doc.css',
        'packages/website-client/client/theme/default.css',
        'packages/website-client/client/theme/cosmetics.css',
        'packages/website-client/client/theme/public.css',
      ]
        .map((p) => `@import "./${p}";`)
        .join('\n'),
      resolveDir: root,
      loader: 'css',
    },
    outfile: resolve(out, 'public.css'),
    bundle: true,
  })
  await build({
    entryPoints: [resolve(root, 'packages/website-client/client/entry.ts')],
    outfile: resolve(out, 'website.mjs'),
    banner: { js: '// @ts-nocheck Generated by build-website-client.mjs' },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    jsx: 'automatic',
    jsxImportSource: '@ketvietlab/ketjs-view',
    target: 'es2022',
    plugins: [
      {
        name: 'website-runtime',
        setup(b) {
          b.onResolve({ filter: /^@ketvietlab\/ketjs-view(\/jsx-runtime)?$/ }, (args) => ({
            path: args.path.endsWith('/jsx-runtime') ? '/_ket/view/jsx-runtime.js' : '/_ket/view/index.js',
            external: true,
          }))
          b.onResolve({ filter: /^@ketvietlab\/ketsuite\/livedoc$/ }, () => ({
            path: '/_ket/asset/livedoc/live-doc.mjs',
            external: true,
          }))
          b.onResolve({ filter: /^@ketvietlab\/ketsuite\/ui\/icons$/ }, () => ({
            path: resolve(root, 'packages/ketsuite/src/ui/icons.ts'),
          }))
          b.onResolve({ filter: /^@ketvietlab\/design-system$/ }, () => ({
            path: resolve(root, 'packages/design-system/src/index.ts'),
          }))
        },
      },
    ],
    minify: true,
    logLevel: 'warning',
  })
  await build({
    stdin: {
      contents: [
        'packages/design-system/src/styles.css',
        'packages/ketsuite/src/ui/client/live-doc.css',
        'packages/website-client/client/ds-gaps.css',
        'packages/website-client/client/styles.css',
        'packages/website-client/client/theme/default.css',
        'packages/website-client/client/theme/cosmetics.css',
      ]
        .map((p) => `@import "./${p}";`)
        .join('\n'),
      resolveDir: root,
      loader: 'css',
    },
    outfile: resolve(out, 'website.css'),
    bundle: true,
    loader: { '.woff2': 'file' },
    assetNames: 'fonts/[name]-[hash]',
    logLevel: 'warning',
  })
  cpSync(resolve(root, 'packages/website-client/client/theme'), resolve(out, 'theme'), {
    recursive: true,
    filter: (source) => !/\.tsx?$/.test(source),
  })
}
