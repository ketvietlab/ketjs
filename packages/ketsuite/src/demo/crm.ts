export async function seedCrm(call: Call): Promise<string[]> {
  const ids: string[] = []
  for (const item of CASES) {
    const saved = await call('crm.case.save', {
      id: item.id,
      kind: item.kind,
      name: item.name,
      partnerId: item.partnerId,
      stageId: item.stageId,
      priority: item.priority,
      description: item.description,
      idempotencyKey: `seed:${item.id}`,
      ...(item.expectedRevenue ? { expectedRevenue: item.expectedRevenue } : {}),
    })
    if (item.close === 'won') {
      await call('crm.case.markWon', {
        id: item.id,
        expectedVersion: Number(saved.version),
        idempotencyKey: `seed:${item.id}:won`,
      })
    } else if (item.close === 'lost') {
      await call('crm.case.markLost', {
        id: item.id,
        expectedVersion: Number(saved.version),
        lostReason: item.lostReason ?? 'Không còn phù hợp với nhu cầu hiện tại',
        idempotencyKey: `seed:${item.id}:lost`,
      })
    }
    ids.push(item.id)
  }
  return ids
}
